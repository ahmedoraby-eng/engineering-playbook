"""A picture of DFP's flow, drawn from the table in client.py, and a read-only check of it against Jira.

The picture is generated, never drawn by hand, so it can't differ from the table the code runs on:

    python -m atl_agent.flowchart            # print the picture (Markdown with a Mermaid diagram)
    python -m atl_agent.flowchart --write    # rewrite standards/dfp-flow.md; a test fails when it is out of date
    python -m atl_agent.flowchart check      # ask Jira's GET /transitions whether the table's moves exist

`check` changes nothing: it makes GET calls only, as an agent, with that agent's Keychain token. Today every DFP
transition is global (any status reaches any status), so besides the table's moves it reports how many extra moves
Jira allows. That is a finding, not a failure; only a move of the table that Jira lacks makes `check` exit 1.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

from .client import (
    FLOW,
    JIRA_ACCOUNTS,
    LAST_ENGINEER,
    AtlClient,
    AtlError,
    default_cloud_id,
    keychain_token,
)

PICTURE = Path(__file__).resolve().parents[2] / "standards" / "dfp-flow.md"

# The moves other commands make (client.py: jira_ready, jira_return, jira_start, jira_dismiss; close.py). They are not
# rows of FLOW, so the picture draws them dashed, with the command that makes each one.
